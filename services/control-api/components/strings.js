const TABLES = { projects: P_S, monitoring: M_S, growth: G_S, settings: ST_S };

// Merge the base table with a section's table, like each prototype screen did
// (`L = { ...S[lang], ...P_S[lang] }`). `section` omitted -> base only.
export function tFor(section, lang) {
  const base = S[lang] || S.ar;
  const extra = section && TABLES[section] ? TABLES[section][lang] || TABLES[section].ar : {};
  return { ...base, ...extra };
}
