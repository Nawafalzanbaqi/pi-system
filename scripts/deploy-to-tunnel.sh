#!/usr/bin/env bash
# ===========================================================================
# pi-system — deploy a generated project to the live Pi behind Cloudflare Tunnel
# ---------------------------------------------------------------------------
# Publishes a project created by scripts/new-project.sh to the PUBLIC internet
# through a Cloudflare Tunnel — WITHOUT opening any inbound port on the Pi — with
# a real public Let's Encrypt certificate issued by Caddy's own ACME (no manual
# Cloudflare certificate). It automates steps b-g of docs/cloudflare-tunnel.md:
#
#   b. copy services/<name>/ to the Pi (rsync or scp over SSH)
#   c. (CHECK ONLY) verify the one-time cloudflared + tunnel setup exists
#   d. ensure the one-time Caddy `http_port` global block on the Pi's Caddyfile
#   e. add the Cloudflare DNS record:  cloudflared tunnel route dns <tunnel> <fqdn>
#   f. ensure the project's Caddy site block on the Pi's Caddyfile (Let's Encrypt
#      is automatic — its `tls {$CADDY_TLS}` switches to ACME once ACME_EMAIL set)
#   g. set BASE_DOMAIN/ACME_EMAIL in the Pi's .env, reload Caddy, start the project
#
# This script runs on YOUR DEV MACHINE and drives the Pi over SSH. On Windows run
# it from Git Bash or WSL (it needs ssh / scp / rsync).
#
# It NEVER opens inbound ports, NEVER touches the databases/auth/base compose, and
# NEVER prints secret values. Every Pi file it edits is backed up first.
#
# The ONE-TIME Pi setup (install cloudflared, `cloudflared tunnel login/create`,
# the ingress config + systemd service) is NOT done here — it needs a browser
# login and is described in docs/cloudflare-tunnel.md (steps c & d). This script
# verifies it exists and stops with a pointer if it doesn't.
#
# Usage:
#   ./scripts/deploy-to-tunnel.sh --name <project> --subdomain <sub> --email <acme-email>
#                                 [--base-domain <domain>] [--start-db] [--yes]
#
#     --name <project>     a project generated by scripts/new-project.sh
#     --subdomain <sub>    public DNS label (default: <project>)
#     --email <addr>       ACME e-mail for Let's Encrypt (sets ACME_EMAIL on the Pi)
#     --base-domain <d>    your Cloudflare domain (overrides the CONFIG default)
#     --start-db           also start the project's shared DB engine on the Pi
#     --yes                don't prompt for confirmation (non-interactive)
#     -h, --help           show this help and exit
# ===========================================================================
set -euo pipefail

# ===========================================================================
# CONFIG — Pi connection + environment. Edit these to match your setup, OR
# override any of them from the environment without editing this file, e.g.:
#   PI_HOST=10.0.0.5 BASE_DOMAIN=example.com ./scripts/deploy-to-tunnel.sh ...
# (This is the only block you should normally need to touch.)
# ---------------------------------------------------------------------------
PI_HOST="${PI_HOST:-raspberrypi.local}"                  # hostname or IP of the live Pi
PI_USER="${PI_USER:-pi}"                                  # SSH user on the Pi
PI_SSH_PORT="${PI_SSH_PORT:-22}"                          # SSH port
PI_PROJECT_DIR="${PI_PROJECT_DIR:-/home/${PI_USER}/pi-system}"  # this repo's path on the Pi
BASE_DOMAIN="${BASE_DOMAIN:-}"                            # your Cloudflare domain, e.g. example.com
TUNNEL_NAME="${TUNNEL_NAME:-pi-system}"                   # the one-time cloudflared tunnel name
SSH_KEY="${SSH_KEY:-}"                                    # optional: path to a private key (ssh -i)
# ===========================================================================

# --- Resolve project root (the parent of this scripts/ directory) ----------
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
cd "${PROJECT_ROOT}"

# --- Tiny coloured loggers -------------------------------------------------
log()  { printf '\033[0;32m[deploy-tunnel]\033[0m %s\n' "$*"; }
warn() { printf '\033[0;33m[warn]\033[0m %s\n' "$*" >&2; }
err()  { printf '\033[0;31m[error]\033[0m %s\n' "$*" >&2; }

LOCAL_CADDYFILE="${PROJECT_ROOT}/services/proxy/Caddyfile"
PI_CADDYFILE="${PI_PROJECT_DIR}/services/proxy/Caddyfile"
PI_ENV="${PI_PROJECT_DIR}/.env"

usage() {
  cat >&2 <<EOF
Usage: ./scripts/deploy-to-tunnel.sh --name <project> --subdomain <sub> --email <acme-email>
                                     [--base-domain <domain>] [--start-db] [--yes]

  --name <project>     a project generated by ./scripts/new-project.sh
  --subdomain <sub>    public DNS label (default: <project>)
  --email <addr>       ACME e-mail for Let's Encrypt (sets ACME_EMAIL on the Pi)
  --base-domain <d>    your Cloudflare domain (overrides the CONFIG default)
  --start-db           also start the project's shared DB engine on the Pi
  --yes                don't prompt for confirmation (non-interactive)
  -h, --help           show this help and exit

Pi connection comes from the CONFIG block at the top of this script (or env vars):
  PI_HOST=${PI_HOST}  PI_USER=${PI_USER}  PI_SSH_PORT=${PI_SSH_PORT}
  PI_PROJECT_DIR=${PI_PROJECT_DIR}
  TUNNEL_NAME=${TUNNEL_NAME}  BASE_DOMAIN=${BASE_DOMAIN:-<unset>}

Example:
  ./scripts/deploy-to-tunnel.sh --name shop --subdomain shop --email you@example.com
EOF
}

# --- Parse arguments -------------------------------------------------------
NAME="" SUBDOMAIN="" EMAIL="" START_DB=0 ASSUME_YES=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --name)          [[ $# -ge 2 ]] || { err "--name requires a value.";        usage; exit 1; }; NAME="$2";        shift 2 ;;
    --name=*)        NAME="${1#*=}";        shift ;;
    --subdomain)     [[ $# -ge 2 ]] || { err "--subdomain requires a value.";   usage; exit 1; }; SUBDOMAIN="$2";   shift 2 ;;
    --subdomain=*)   SUBDOMAIN="${1#*=}";   shift ;;
    --email)         [[ $# -ge 2 ]] || { err "--email requires a value.";       usage; exit 1; }; EMAIL="$2";       shift 2 ;;
    --email=*)       EMAIL="${1#*=}";       shift ;;
    --base-domain)   [[ $# -ge 2 ]] || { err "--base-domain requires a value."; usage; exit 1; }; BASE_DOMAIN="$2"; shift 2 ;;
    --base-domain=*) BASE_DOMAIN="${1#*=}"; shift ;;
    --start-db)      START_DB=1;            shift ;;
    -y|--yes)        ASSUME_YES=1;          shift ;;
    -h|--help)       usage; exit 0 ;;
    *)               err "Unknown argument: '$1'."; usage; exit 1 ;;
  esac
done

# --- Defaults + validation -------------------------------------------------
SUBDOMAIN="${SUBDOMAIN:-${NAME}}"

if [[ -z "${NAME}" || -z "${EMAIL}" ]]; then
  err "Missing required value(s). Need --name and --email."
  usage; exit 1
fi
if [[ -z "${BASE_DOMAIN}" ]]; then
  err "BASE_DOMAIN is not set. Pass --base-domain <domain> or set it in the CONFIG block / env."
  err "It must be a domain you control in Cloudflare (e.g. example.com)."
  exit 1
fi
if ! [[ "${NAME}" =~ ^[a-z][a-z0-9-]{0,38}[a-z0-9]$ ]]; then
  err "Invalid project name: '${NAME}' (lowercase, letter first, [a-z0-9-], 2-40 chars, no trailing '-')."
  exit 1
fi
if ! [[ "${SUBDOMAIN}" =~ ^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$ ]]; then
  err "Invalid subdomain: '${SUBDOMAIN}' (must be a DNS label: [a-z0-9-], no leading/trailing '-')."
  exit 1
fi
if ! [[ "${EMAIL}" =~ ^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$ ]]; then
  err "Invalid e-mail: '${EMAIL}'."
  exit 1
fi
if ! [[ "${BASE_DOMAIN}" =~ ^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$ ]]; then
  err "Invalid base domain: '${BASE_DOMAIN}' (expected something like example.com)."
  exit 1
fi

FQDN="${SUBDOMAIN}.${BASE_DOMAIN}"
FRAGMENT="${PROJECT_ROOT}/services/${NAME}/${NAME}.compose.yml"

# The project must exist locally (it carries the files + the Caddy block we ship).
if [[ ! -f "${FRAGMENT}" ]]; then
  err "Project '${NAME}' not found locally (missing ${FRAGMENT})."
  err "Generate it first:  ./scripts/new-project.sh --name ${NAME} --preset <preset> --subdomain ${SUBDOMAIN}"
  exit 1
fi
if [[ ! -f "${LOCAL_CADDYFILE}" ]]; then
  err "Local Caddyfile not found at ${LOCAL_CADDYFILE}."
  exit 1
fi

# The DB engine the project uses (from the fragment's machine-readable metadata).
DBENGINE="$(grep -E '^# pi-system-db:' "${FRAGMENT}" | head -n1 | awk '{print $3}' || true)"

# --- SSH / copy plumbing ---------------------------------------------------
PI_TARGET="${PI_USER}@${PI_HOST}"
SSH_ARGS=(-p "${PI_SSH_PORT}")
[[ -n "${SSH_KEY}" ]] && SSH_ARGS+=(-i "${SSH_KEY}")
run_pi() { ssh "${SSH_ARGS[@]}" "${PI_TARGET}" "$@"; }

copy_project() {
  local src="${PROJECT_ROOT}/services/${NAME}/"
  local dest_dir="${PI_PROJECT_DIR}/services/${NAME}"
  if command -v rsync >/dev/null 2>&1; then
    local rsh="ssh -p ${PI_SSH_PORT}"
    [[ -n "${SSH_KEY}" ]] && rsh="${rsh} -i ${SSH_KEY}"
    rsync -az --delete -e "${rsh}" "${src}" "${PI_TARGET}:${dest_dir}/"
  else
    run_pi "mkdir -p '${dest_dir}'"
    local scp_args=(-P "${PI_SSH_PORT}" -r)
    [[ -n "${SSH_KEY}" ]] && scp_args+=(-i "${SSH_KEY}")
    scp "${scp_args[@]}" "${src}." "${PI_TARGET}:${dest_dir}/"
  fi
}

confirm() {
  [[ "${ASSUME_YES}" -eq 1 ]] && return 0
  if [[ ! -t 0 ]]; then
    err "Refusing to run non-interactively without --yes (this makes a project public)."
    exit 1
  fi
  local ans=""
  read -r -p "Proceed with the deployment above? [y/N] " ans
  case "${ans}" in y|Y|yes|YES) return 0 ;; *) err "Aborted — nothing was changed."; exit 1 ;; esac
}

# --- The one-time fallback Caddy global block (added only if the Pi lacks it) ---
GLOBAL_BLOCK="$(printf '%s\n' \
  '# >>> pi-system tunnel (one-time) >>>' \
  '# pi-system-tunnel: http_port' \
  '{' \
  $'\thttp_port 80' \
  '}' \
  '# <<< pi-system tunnel (one-time) <<<' \
  '')"

# ===========================================================================
# Plan + confirm
# ===========================================================================
echo
log "Deployment plan:"
cat <<EOF
   Project          : ${NAME}  (db: ${DBENGINE:-none})
   Public URL       : https://${FQDN}
   Pi               : ${PI_TARGET}:${PI_SSH_PORT}   (${PI_PROJECT_DIR})
   Tunnel           : ${TUNNEL_NAME}
   Will, on the Pi  : copy the project · ensure Caddy http_port + site block ·
                      route DNS ${FQDN} -> tunnel · set BASE_DOMAIN/ACME_EMAIL in
                      .env (backup first) · reload Caddy · start the project$( [[ "${START_DB}" -eq 1 ]] && printf ' · start the %s DB' "${DBENGINE}" )
   Will NOT         : open inbound ports · touch databases/auth/base compose ·
                      print or change any secret values
EOF
echo
warn "This makes '${NAME}' reachable from the PUBLIC internet at https://${FQDN}."
confirm

# ===========================================================================
# 0. Pre-flight: can we reach the Pi?
# ===========================================================================
log "Checking SSH connectivity to ${PI_TARGET} ..."
if ! run_pi "true"; then
  err "Could not SSH to ${PI_TARGET} on port ${PI_SSH_PORT}."
  err "Fix the CONFIG block (PI_HOST/PI_USER/PI_SSH_PORT/SSH_KEY) or your SSH access."
  exit 1
fi
if ! run_pi "test -d '${PI_PROJECT_DIR}'"; then
  err "Repo not found on the Pi at ${PI_PROJECT_DIR} (set PI_PROJECT_DIR)."
  exit 1
fi

# ===========================================================================
# c. Check the ONE-TIME cloudflared setup exists (we do not create it here)
# ===========================================================================
log "Verifying the one-time cloudflared setup on the Pi ..."
if ! run_pi "command -v cloudflared >/dev/null 2>&1"; then
  err "cloudflared is not installed on the Pi."
  err "Do the one-time setup first — see docs/cloudflare-tunnel.md (step c)."
  exit 1
fi
if ! run_pi "test -f /etc/cloudflared/config.yml"; then
  err "No /etc/cloudflared/config.yml on the Pi — the tunnel isn't configured."
  err "Do the one-time setup first — see docs/cloudflare-tunnel.md (steps c & d)."
  exit 1
fi
if ! run_pi "cloudflared tunnel list 2>/dev/null | grep -qw '${TUNNEL_NAME}'"; then
  err "Tunnel '${TUNNEL_NAME}' not found (cloudflared tunnel list)."
  err "Create it once with: cloudflared tunnel create ${TUNNEL_NAME}  (see the guide)."
  exit 1
fi
if ! run_pi "systemctl is-active --quiet cloudflared"; then
  warn "The cloudflared systemd service is not active — start it with:"
  warn "  sudo systemctl enable --now cloudflared   (continuing anyway)"
fi
log "One-time tunnel setup looks good."

# ===========================================================================
# b. Copy the project to the Pi
# ===========================================================================
log "Copying services/${NAME}/ to the Pi ..."
copy_project
log "Project files synced to ${PI_PROJECT_DIR}/services/${NAME}/."

# ===========================================================================
# d. Ensure the one-time Caddy http_port global block on the Pi's Caddyfile
# ===========================================================================
if run_pi "grep -qF 'pi-system-tunnel: http_port' '${PI_CADDYFILE}' 2>/dev/null"; then
  log "Caddy http_port global block already present on the Pi."
else
  warn "Adding the one-time Caddy http_port global block to the Pi's Caddyfile (backup first) ..."
  printf '%s\n' "${GLOBAL_BLOCK}" | run_pi "cp '${PI_CADDYFILE}' '${PI_CADDYFILE}.bak-\$(date +%Y%m%d-%H%M%S)' && cat - '${PI_CADDYFILE}' > '${PI_CADDYFILE}.tmp' && mv '${PI_CADDYFILE}.tmp' '${PI_CADDYFILE}'"
  log "Caddy http_port global block added."
fi

# ===========================================================================
# f. Ensure the project's Caddy site block on the Pi's Caddyfile
# ===========================================================================
SITE_BEGIN="# >>> pi-system project: ${NAME} >>>"
SITE_END="# <<< pi-system project: ${NAME} <<<"
if run_pi "grep -qF '${SITE_BEGIN}' '${PI_CADDYFILE}' 2>/dev/null"; then
  log "Caddy site block for '${NAME}' already present on the Pi."
else
  # Extract the project's block from the LOCAL Caddyfile (fixed-string match).
  SITE_BLOCK="$(awk -v b="${SITE_BEGIN}" -v e="${SITE_END}" \
    'index($0,b){f=1} f{print} index($0,e){f=0}' "${LOCAL_CADDYFILE}")"
  if [[ -z "${SITE_BLOCK}" ]]; then
    err "Could not find the Caddy block for '${NAME}' in ${LOCAL_CADDYFILE}."
    err "Re-generate the project so the block exists: ./scripts/new-project.sh --name ${NAME} ..."
    exit 1
  fi
  warn "Appending the '${NAME}' Caddy site block to the Pi's Caddyfile (backup first) ..."
  printf '\n%s\n' "${SITE_BLOCK}" | run_pi "cp '${PI_CADDYFILE}' '${PI_CADDYFILE}.bak-\$(date +%Y%m%d-%H%M%S)' && cat >> '${PI_CADDYFILE}'"
  log "Caddy site block for '${NAME}' added (tls {\$CADDY_TLS} -> Let's Encrypt once ACME_EMAIL is set)."
fi

# ===========================================================================
# g (env). Set BASE_DOMAIN + ACME_EMAIL in the Pi's .env (backup, idempotent)
# ===========================================================================
if ! run_pi "test -f '${PI_ENV}'"; then
  err ".env not found on the Pi at ${PI_ENV}. Run ./scripts/setup.sh on the Pi first."
  exit 1
fi
log "Setting BASE_DOMAIN=${BASE_DOMAIN} and ACME_EMAIL=${EMAIL} in the Pi's .env (backup first) ..."
run_pi "ENVF='${PI_ENV}' BASE_DOMAIN='${BASE_DOMAIN}' ACME_EMAIL='${EMAIL}' bash -s" <<'REMOTE'
set -euo pipefail
cp "$ENVF" "$ENVF.bak-$(date +%Y%m%d-%H%M%S)"
setkv() {
  local k="$1" v="$2"
  if grep -qE "^${k}=" "$ENVF"; then
    sed -i "s|^${k}=.*|${k}=${v}|" "$ENVF"   # domains/emails contain no | so this is safe
  else
    printf '%s=%s\n' "$k" "$v" >> "$ENVF"
  fi
}
setkv BASE_DOMAIN "$BASE_DOMAIN"
setkv ACME_EMAIL  "$ACME_EMAIL"
REMOTE
log ".env updated (a timestamped .env.bak-* was saved)."

# ===========================================================================
# e. Add the Cloudflare DNS record pointing the subdomain at the tunnel
# ===========================================================================
log "Routing ${FQDN} through tunnel '${TUNNEL_NAME}' (creates a proxied CNAME) ..."
if run_pi "cloudflared tunnel route dns '${TUNNEL_NAME}' '${FQDN}'"; then
  log "DNS route ensured: ${FQDN} -> ${TUNNEL_NAME}."
else
  warn "cloudflared route returned non-zero. Usually this means the record already"
  warn "exists (fine) — or the SSH user lacks ~/.cloudflared/cert.pem. Verify the"
  warn "record is a PROXIED CNAME to <tunnel-id>.cfargotunnel.com in the dashboard."
fi

# ===========================================================================
# g (start). Reload Caddy with the new env/Caddyfile, then start the project
# ===========================================================================
log "Reloading Caddy and starting '${NAME}' on the Pi ..."
run_pi "PI_PROJECT_DIR='${PI_PROJECT_DIR}' NAME='${NAME}' DBENGINE='${DBENGINE}' START_DB='${START_DB}' bash -s" <<'REMOTE'
set -euo pipefail
cd "$PI_PROJECT_DIR"
# Recreate Caddy so it re-reads .env (BASE_DOMAIN/ACME_EMAIL), then reload Caddyfile.
./scripts/start-proxy.sh
CN="$(grep -E '^COMPOSE_PROJECT_NAME=' .env | cut -d= -f2-)"; CN="${CN:-pi-system}"
if ! docker exec "${CN}_caddy" caddy reload --config /etc/caddy/Caddyfile 2>/dev/null; then
  echo "[warn] caddy reload skipped (start-proxy.sh already applied changes)"
fi
if [ "$START_DB" = "1" ] && [ -n "$DBENGINE" ] && [ "$DBENGINE" != "none" ]; then
  ./scripts/db.sh "$DBENGINE" up
fi
./scripts/project.sh up "$NAME"
REMOTE

# ===========================================================================
# Done — summary, secret reminder, verification
# ===========================================================================
echo
log "Deployed '${NAME}' to ${PI_TARGET} behind the Cloudflare Tunnel."
log "Public URL:  https://${FQDN}"
echo

# Remind about project-specific secrets (e.g. content-admin's CMS_*), which are
# git-ignored and live ONLY in the Pi's .env — we never copy or invent them.
shopt -s nullglob
MOD_FRAGMENTS=("${PROJECT_ROOT}/services/${NAME}/${NAME}".*.compose.yml)
shopt -u nullglob
if ((${#MOD_FRAGMENTS[@]})); then
  warn "This project has module fragment(s):"
  for f in "${MOD_FRAGMENTS[@]}"; do warn "  - ${f##*/}"; done
  warn "If a module needs secrets (e.g. content-admin's CMS_KEY/CMS_SECRET/CMS_ADMIN_*/"
  warn "CMS_DB_PASSWORD), set them in the Pi's .env BEFORE first boot — copy the"
  warn "'# >>> PROJECT: ${NAME} >>>' section from .env.example and fill it in."
fi
if [[ -n "${DBENGINE}" && "${DBENGINE}" != "none" && "${START_DB}" -ne 1 ]]; then
  warn "This project uses the '${DBENGINE}' database. If it isn't running on the Pi:"
  warn "  ssh ${PI_TARGET} 'cd ${PI_PROJECT_DIR} && ./scripts/db.sh ${DBENGINE} up'"
  warn "  (or re-run with --start-db)"
fi

cat <<EOF

Verify (from anywhere — the cert is issued on first request, give it ~30s):
  dig +short ${FQDN}                         # resolves to Cloudflare (proxied)
  curl -I https://${FQDN}                     # real, publicly-trusted cert; 200/redirect
  ssh ${PI_TARGET} 'docker logs --tail=50 \$(grep -E "^COMPOSE_PROJECT_NAME=" ${PI_ENV} | cut -d= -f2- | sed "s/^\$/pi-system/")_caddy'
                                              # look for "certificate obtained successfully"

Inbound :80/:443 on the Pi stay CLOSED — traffic only arrives through the tunnel.
Full walkthrough + troubleshooting: docs/cloudflare-tunnel.md
EOF
